#!/usr/bin/env node
/* Builds wares_render.wasm and writes renderer/js/wares-render.wasm.js (base64, loaded without fetch so the CSP stays strict).
   Needs: rustup target add wasm32-unknown-unknown   (the prebuilt result is committed, so most people never run this) */
const { spawnSync } = require('child_process');
const fs = require('fs');
const path = require('path');
const dir = __dirname;
const r = spawnSync('cargo', ['build', '--release', '--target', 'wasm32-unknown-unknown'], { cwd: dir, stdio: 'inherit', shell: process.platform === 'win32' });
if (r.status !== 0) process.exit(r.status || 1);
const wasm = fs.readFileSync(path.join(dir, 'target', 'wasm32-unknown-unknown', 'release', 'wares_render.wasm'));
const out = path.join(dir, '..', '..', 'renderer', 'js', 'wares-render.wasm.js');
fs.writeFileSync(out, `/* generated by native/render/build.js - do not edit */\nwindow.WARES_RENDER_WASM = '${wasm.toString('base64')}';\n`);
console.log(`wrote ${path.relative(process.cwd(), out)} (${wasm.length} bytes of wasm)`);
